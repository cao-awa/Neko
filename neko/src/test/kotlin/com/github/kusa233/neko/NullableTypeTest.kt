                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("1\nnull\n", output)
    }

    // ------------------------------------------------------------------ boxing a nullable primitive

    @Test
    fun `a nullable primitive holds a value and prints it`() {
        // An `int?` is a `java.lang.Integer`, so `x: int? = 1` has to box the literal. Without that
        // conversion the class file would fail to verify, which is why this test runs the program.
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: int? = 1",
                "        b: int? = null",
                "        c: long? = 2L",
                "        d: bool? = true",
                "        println(a)",
                "        println(b)",
                "        println(c)",
                "        println(d)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("1\nnull\n2\ntrue\n", output)
    }

    @Test
    fun `a nullable primitive can be read back, reassigned and returned`() {
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun pick(flag: bool): int? {",
                "        if (flag) {",
                "            return 5",
                "        }",
                "        return null",
                "    }",
                "",
                "    fun main() {",
                "        a: int? = pick(true)",
                "        println(a)",
                "        a = pick(false)",
                "        println(a)",
                "        a = 9",
                "        println(a)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("5\nnull\n9\n", output)
    }

    @Test
    fun `a nullable value can be stored in and read from a field`() {
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    var value: int? = null",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder = Holder()",
                "            println(h.value)",
                "            h.value = 3",
                "            println(h.value)",
                "            h.value = null",
                "            println(h.value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("null\n3\nnull\n", output)
    }

    // ------------------------------------------------------------------ equality

    @Test
    fun `comparing a null value against null does not throw`() {
        // The reason `==` had to change: the only way to ask whether a nullable value is absent is to
        // compare it against `null`, so the comparison must survive the absent case.
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: string? = null",
                "        b: string? = \"text\"",
                "        println(a == null)",
                "        println(a != null)",
                "        println(b == null)",
                "        println(b != null)",
                "        println(null == a)",
                "        println(null != a)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("true\nfalse\nfalse\ntrue\ntrue\nfalse\n", output)
    }

    @Test
    fun `comparing a non-nullable value against null is refused`() {
        // The answer is known without running anything, so it is reported rather than emitted — and
        // the message points at the operand that is not nullable, rather than at the `null`.
        messageFor(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: string = \"text\"",
                "        println(a == null)",
                "    }",
                "}",
            ),
            "which is not nullable, so it can never be null",
        )
    }

    @Test
    fun `two nullable values compare by value`() {
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: int? = 1",
                "        b: int? = 1",
                "        c: int? = 2",
                "        d: int? = null",
                "        println(a == b)",
                "        println(a == c)",
                "        println(a == 1)",
                "        println(a != c)",
                "        println(d == null)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("true\nfalse\ntrue\ntrue\ntrue\n", output)
    }

    @Test
    fun `two plain objects can still be compared`() {
        // `==` reaches `java.util.Objects.equals` now rather than a virtual call on `Object`. The
        // answer for two classes that declare no `equals` is unchanged, which is the whole point of
        // routing through the JDK's method instead of a narrower owner.
        val program = TestSupport.load(
            TestSupport.file(
                "class Plain {",
                "    static {",
                "        fun make(): Plain {",
                "            return Plain()",
                "        }",
                "",
                "        fun main() {",
                "            a: Plain = make()",
                "            b: Plain = make()",
                "            println(a == b)",
                "            println(a == a)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Plain", "main") }
        assertEquals("false\ntrue\n", output)
    }

    // ------------------------------------------------------------------ dereferencing

    @Test
    fun `reading a field of a nullable value is refused`() {
        val source = TestSupport.file(
            "class Holder {",
            "    val value: int = 1",
            "}",
            "",
            "class Main {",
            "    static {",
            "        fun main() {",
            "            h: Holder? = null",
            "            println(h.value)",
            "        }",
            "    }",
            "}",
        )
        messageFor(source, "cannot access member 'value' on a value of type Holder?")
    }

    @Test
    fun `calling a member of a nullable value is refused`() {
        val source = TestSupport.file(
            "class Holder {",
            "    fun get(): int {",
            "        return 1",
            "    }",
            "}",
            "",
            "class Main {",
            "    static {",
            "        fun main() {",
            "            h: Holder? = null",
            "            println(h.get())",
            "        }",
            "    }",
            "}",
        )
        messageFor(source, "cannot call member 'get' on a value of type Holder?")
    }

    @Test
    fun `assigning a field of a nullable value is refused`() {
        // `?.` guards a read, so there is no safe spelling for a write and the message does not
        // pretend otherwise.
        messageFor(
            TestSupport.file(
                "class Holder {",
                "    var value: int = 1",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = null",
                "            h.value = 2",
                "        }",
                "    }",
                "}",
            ),
            "cannot assign to member 'value' on a value of type Holder?, which may be null",
        )
    }

    @Test
    fun `a nullable value can be tested and then read through a safe call`() {
        // `?.` is still the way to read a value the code has not tested, and testing does not remove
        // the need for it *after* the test — narrowing is about the branches of the test, not about
        // everything that follows it.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h == null) {",
                "                println(\"absent\")",
                "            } else {",
                "                println(\"present\")",
                "            }",
                "            println(h?.value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("present\n4\n", output)
    }

    @Test
    fun `a null test narrows the type inside the branch that knows the answer`() {
        // The whole point of narrowing: the branch that has just established the value is there reads
        // it as a plain `Holder`, so an ordinary member access works and `?.` is not needed.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                println(h.value)",
                "            }",
                "            if (h == null) {",
                "                println(\"absent\")",
                "            } else {",
                "                println(h.value + 1)",
                "            }",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("4\n5\n", output)
    }

    @Test
    fun `a narrowed value is refused where a nullable type is expected`() {
        // What narrowing does *not* do is change the declaration. The call inside the branch is fine,
        // because that path proved the value is there; the identical call *after* the `if` is still
        // handing over a `Holder?` and is refused — the same expression, decided by where it stands.
        messageFor(
            TestSupport.file(
                "class Holder {",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun take(h: Holder) {",
                "            println(\"taken\")",
                "        }",
                "",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                take(h)",
                "            }",
                "            take(h)",
                "        }",
                "    }",
                "}",
            ),
            "argument 1 of 'take' is declared as Holder but has type Holder?",
        )
    }

    @Test
    fun `a narrowed value may be assigned and returned as the non-nullable type`() {
        // On the path that proved it, the value really is a `Holder`, so every place that wants one
        // accepts it: a variable's declared type, a `return`, and a parameter.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun pick(h: Holder?): Holder {",
                "            if (h == null) {",
                "                return Holder()",
                "            }",
                "            return h",
                "        }",
                "",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                x: Holder = h",
                "                println(x.value)",
                "            }",
                "            println(pick(null).value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("4\n4\n", output)
    }

    @Test
    fun `a narrowing is not restored over a write in a nested branch`() {
        // The write is conditional, so it *may* have run: the fact cannot be put back afterwards, and
        // the read after the inner `if` has to be refused exactly as a plain nullable read would be.
        messageFor(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            clear: bool = false",
                "            if (h != null) {",
                "                if (clear) {",
                "                    h = null",
                "                }",
                "                println(h.value)",
                "            }",
                "        }",
                "    }",
                "}",
            ),
            "write 'h?.value' to do nothing when it is absent",
        )
    }

    @Test
    fun `a narrowing does not outlive the branch that proved it`() {
        // A fact proved inside an arm is about that run through the arm. Leaving the `if` drops it,
        // so the read after the test is nullable again — which is what keeps `h` honest when the
        // value really was absent.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = null",
                "            if (h != null) {",
                "                println(h.value)",
                "            }",
                "            println(h?.value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("null\n", output)
    }

    @Test
    fun `a narrowing does not survive a write to the value`() {
        // The fact is about the value that was tested, and the write puts a different one there.
        // `h` is nullable again afterwards, so the plain read is refused and `?.` still works.
        messageFor(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                h = null",
                "                println(h.value)",
                "            }",
                "        }",
                "    }",
                "}",
            ),
            "write 'h?.value' to do nothing when it is absent",
        )
    }

