package com.github.kusa233.neko

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Tests for `T?`, the `null` literal, `?.` and smart cast.
 *
 * The feature is one rule with four parts: `int?` is the *only* place `null` may be written, a
 * nullable value may only be handed to another nullable type, the one thing that may be done with
 * one — reaching into it — has to be spelled `?.` so that the absent case is written down, and a test
 * that settles whether the value is there narrows it for the code the answer covers.
 *
 * Most tests here compile *and run* a program, because half of what the feature promises is about what
 * happens at run time: `x == null` must answer, not throw, and an `int?` holding `1` must print `1`
 * rather than failing to verify. A test that only asserted on the diagnostics would not notice the
 * difference — and a narrowing is exactly the kind of change that can leave the analyzer and the
 * generated byte code disagreeing about whether a value is boxed.
 */
class NullableTypeTest {

    private fun messageFor(source: String, fragment: String) {
        val messages = TestSupport.messages(TestSupport.compile(source))
        assertTrue(
            messages.any { it.contains(fragment) },
            "expected a message containing '$fragment', but got: $messages",
        )
    }

    // ------------------------------------------------------------------ the null literal

    @Test
    fun `a nullable type accepts null and a value of its inner type`() {
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: string? = null",
                "        b: string? = \"text\"",
                "        c: string = \"text\"",
                "        d: string? = c",
                "        println(a)",
                "        println(b)",
                "        println(d)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("null\ntext\ntext\n", output)
    }

    @Test
    fun `null cannot be assigned to a non-nullable type`() {
        // The check that carries the whole feature: this is the assignment that would otherwise be a
        // `NullPointerException` at the first use of the variable.
        messageFor(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: string = null",
                "        println(a)",
                "    }",
                "}",
            ),
            "'null' may only be used where a nullable type is expected",
        )
    }

    @Test
    fun `null with no context at all is refused`() {
        // Nothing in `null` says which type it is absent from, so a use with no expected type has no
        // type to be — the message says so rather than inventing one.
        messageFor(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        x = null",
                "        println(x)",
                "    }",
                "}",
            ),
            "nothing here says what type it should be absent from",
        )
    }

    @Test
    fun `a second question mark is refused`() {
        // `int??` would mean a nullable nullable, which is the same type as a nullable one. Refusing
        // it is what keeps `unwrapNullable` a single unwrapping everywhere it is used.
        messageFor(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        a: string?? = null",
                "        println(a)",
                "    }",
                "}",
            ),
            "nullable only once",
        )
    }

    @Test
    fun `null as an overloaded call's argument is refused`() {
        // `println` has one overload per built-in type, so no single parameter type is there to be
        // read from and the argument is analysed without a context — at which point `null` has no
        // type to be. Pinned deliberately: the fix is to name the type, `x: string? = null`, which is
        // the same rule as everywhere else rather than a special case for `println`.
        messageFor(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        println(null)",
                "    }",
                "}",
            ),
            "nothing here says what type it should be absent from",
        )
    }

    @Test
    fun `a null with a name and a type prints as null`() {
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        absent: Object? = null",
                "        println(absent)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("null\n", output)
    }

    // ------------------------------------------------------------------ assignability

    @Test
    fun `a nullable value cannot be used where a non-nullable one is expected`() {
        val source = TestSupport.program(
            "static {",
            "    fun main() {",
            "        a: string? = null",
            "        b: string = a",
            "        println(b)",
            "    }",
            "}",
        )
        messageFor(source, "initializer has type string?")
    }

    @Test
    fun `a non-nullable value may be stored in a nullable one`() {
        // The other direction is always safe, and has to be allowed or every nullable variable would
        // need its initial value spelled twice.
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun main() {",
                "        n: int = 7",
                "        m: int? = n",
                "        println(m)",
                "    }",
                "}",
            ),
        )
        val output =
            program.capturingOutput { program.invoke("com.github.kusa233.test.Test", "main") }
        assertEquals("7\n", output)
    }

    @Test
    fun `a nullable value cannot be passed to a non-nullable parameter`() {
        messageFor(
            TestSupport.program(
                "static {",
                "    fun takes(x: string) {",
                "        println(x)",
                "    }",
                "",
                "    fun main() {",
                "        a: string? = null",
                "        takes(a)",
                "    }",
                "}",
            ),
            "is declared as string but has type string?",
        )
    }

    @Test
    fun `a nullable value may be passed to a nullable parameter`() {
        val program = TestSupport.load(
            TestSupport.program(
                "static {",
                "    fun takes(x: int?) {",
                "        println(x)",
                "    }",
                "",
                "    fun main() {",
                "        takes(1)",
