                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("shown\ndone\n", output)
    }

    @Test
    fun `a safe call result can be tested for null`() {
        // The two features together: `?.` produces the nullable value that `== null` then asks about.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
