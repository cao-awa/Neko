    @Test
    fun `a safe call does not evaluate its arguments when the receiver is absent`() {
        // `?.` is a short circuit for the whole call, not just for the dispatch: a side-effecting
        // argument that was evaluated anyway would be a silent difference from every other language.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    fun get(n: int): int {",
                "        return n",
                "    }",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun noisy(): int {",
                "            println(\"evaluated\")",
                "            return 1",
                "        }",
                "",
                "        fun main() {",
                "            absent: Holder? = null",
                "            println(absent?.get(noisy()))",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("null\n", output)
    }

    @Test
    fun `a safe call can be chained`() {
        // `?.` produces a nullable value, so it can be asked again — which is what makes a chain of
        // them a single expression rather than a nest of `if`s.
        val program = TestSupport.load(
            TestSupport.file(
                "class Inner {",
                "    val value: int = 8",
                "}",
                "",
                "class Outer {",
                "    val inner: Inner? = Inner()",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            present: Outer? = Outer()",
                "            absent: Outer? = null",
                "            println(present?.inner?.value)",
                "            println(absent?.inner?.value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("8\nnull\n", output)
    }

    @Test
    fun `a safe call on a non-nullable receiver is allowed`() {
        // `?.` on something that cannot be absent does nothing, which is a harmless redundancy rather
        // than something to refuse: the receiver may have become nullable by an edit elsewhere.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder = Holder()",
                "            println(h?.value)",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("4\n", output)
    }

    @Test
    fun `a safe call on a function that returns nothing is allowed`() {
        // A call whose value is absent has no value to be absent *from*, so the safe form still just
        // does not call it.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    fun show() {",
                "        println(\"shown\")",
                "    }",
                "}",
                "",
                "class Main {",
                "    static {",
