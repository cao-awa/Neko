    }

    @Test
    fun `a narrowed value may be handed to a non-nullable parameter`() {
        // This is the whole reason narrowing is worth having: inside the branch, the value is known to
        // be there, so it can be used as an ordinary one — including as an argument where a `Holder`
        // and not a `Holder?` is asked for.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun reveal(h: Holder): int {",
                "            return h.value",
                "        }",
                "",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                println(reveal(h))",
                "            }",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("4\n", output)
    }

    @Test
    fun `a write inside a branch drops that branch's narrowing only`() {
        // The write happens after the read, so the read before it is still narrowed; the one after it
        // is not, because the value it tested is gone.
        messageFor(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h != null) {",
                "                println(h.value)",
                "                h = null",
                "                println(h.value)",
                "            }",
                "        }",
                "    }",
                "}",
            ),
            "write 'h?.value' to do nothing when it is absent",
        )
    }

    @Test
    fun `the two arms of an if do not see each other's narrowing`() {
        // Each arm is read under its own test. The `else` of `h == null` proves `h` is there, but the
        // `then` of the *next* `if` does not — a fact is proved by the test that is being read, not by
        // a sibling somewhere else in the source.
        val program = TestSupport.load(
            TestSupport.file(
                "class Holder {",
                "    val value: int = 4",
                "}",
                "",
                "class Main {",
                "    static {",
                "        fun main() {",
                "            h: Holder? = Holder()",
                "            if (h == null) {",
                "                println(\"absent\")",
                "            } else {",
                "                println(h.value)",
                "            }",
                "            if (h != null) {",
                "                println(h.value)",
                "            } else {",
                "                println(\"absent\")",
                "            }",
                "        }",
                "    }",
                "}",
            ),
        )
        val output = program.capturingOutput { program.invoke("com.github.kusa233.test.Main", "main") }
        assertEquals("4\n4\n", output)
    }
