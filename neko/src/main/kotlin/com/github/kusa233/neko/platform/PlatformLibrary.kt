package com.github.kusa233.neko.platform

import java.lang.module.ModuleFinder
import java.lang.module.ModuleReader
import java.util.TreeMap

/**
 * The classes the Java platform provides, as the compiler is prepared to let a program name them.
 *
 * A Neko program may name a class it does not declare: an unqualified capitalized name is looked up
 * in `java.lang` first, and otherwise in the packages the file `import`s. That rule is why this index
 * exists — neither the analyzer's diagnostics nor the IDE's completion can offer a name without
 * something saying what the name is and which package it belongs to, and the compiler already has the
 * only answer that matters, which is the JDK it is running on.
 *
 * The list is read from the running JDK's own modules rather than kept as a table, for the same
 * reason the analyzer asks the platform whether a class exists instead of carrying a list: a JDK
 * gains and loses classes between releases, and a table would be wrong the moment it was written.
 *
 * Only `java.base` is indexed, and that is a considered limit rather than an oversight. It holds
 * `java.lang`, `java.util`, `java.io`, `java.nio`, `java.time`, `java.math`, `java.text`,
 * `java.util.concurrent` and the rest of what a program actually reaches for; every further module is
 * another scan of a module image, and none of them is required for the language to be usable. A class
 * outside `java.base` is still *nameable* — the generated bytecode simply names it, and the JVM
 * resolves it at run time — it just is not offered by completion and cannot be suggested as an
 * automatic import.
 */
object PlatformLibrary {

    /** The module whose packages are indexed. */
    private const val BASE_MODULE = "java.base"

    /** The package an unqualified capitalized name is looked up in first, with no import written. */
    private const val IMPLICIT_PACKAGE = "java.lang"

    /**
     * Simple class names by the package that holds them, e.g. `java.lang` to `String`.
     *
     * Computed once, on first use. Reading it takes a few milliseconds, which is far too slow to
     * repeat while someone is typing but nothing at all as a one-off — hence the laziness, which
     * also keeps the cost off the path of a program that never asks for completion.
     */
    private val classesByPackage: Map<String, List<String>> by lazy { readPlatformClasses() }

    /**
     * The packages that hold at least one class, sorted.
     *
     * This is what an editor needs in order to offer `import java.util.concurrent` rather than making
     * a reader type it: the set of legal import clauses is exactly this, so it is worth exposing
     * rather than being derivable only from the class list.
     */
    val packages: List<String> by lazy { classesByPackage.keys.sorted() }

    /**
     * The classes of `java.lang`, which a program may name without an import.
     *
     * Sorted, so a completion list built from it is stable between runs.
     */
    val javaLangClasses: List<String> get() = classesByPackage[IMPLICIT_PACKAGE].orEmpty()

    /**
     * Every class of the indexed module, as simple name to package, sorted by simple name.
     *
     * A simple name that two indexed packages both declare appears more than once, deliberately: the
     * caller decides what to do about the ambiguity, and hiding one of them would silently pick a
     * winner. ([packagesOf] shows every candidate for one name.)
     */
    val classes: List<ClassLocation> by lazy {
        classesByPackage
            .flatMap { (packageName, names) -> names.map { ClassLocation(it, packageName) } }
            .sortedWith(compareBy({ it.simpleName }, { it.packageName }))
    }

    /**
     * The classes of [packageName], which a program may name when the file imports that package.
     *
     * Empty for a package outside the indexed module, and for one the JDK does not have.
     */
    fun classesIn(packageName: String): List<String> = classesByPackage[packageName].orEmpty()

    /**
     * Whether [packageName] is a package of the indexed module, i.e. whether importing it does
     * anything at all.
     *
     * An `import` of a package with no classes is not an error in the language — the file's own
     * package is the fallback and it may well exist outside the compilation — but a reader who
     * imported a package only to reach a platform class is better served by knowing the name is not
     * there.
     */
    fun hasPackage(packageName: String): Boolean = packageName in classesByPackage

    /**
     * Every package of the indexed module that declares a class named [simpleName], sorted.
     *
     * Usually empty (the class is not a platform class) or a single entry. More than one is the
     * genuinely awkward case — `java.util.Timer` and `javax.swing.Timer` would be one if both were
     * indexed — and it is answered with every candidate rather than with a guess, so a caller can
     * report the ambiguity instead of inserting an import that resolves to the wrong class.
     *
     * `java.lang` is *not* filtered out here even though it needs no import: a caller asking what
     * package a name belongs to is asking a factual question, and the caller knows whether it is
     * inserting an import or merely labelling a completion row.
     */
    fun packagesOf(simpleName: String): List<String> = classesByPackage
        .filterValues { simpleName in it }
        .keys
        .sorted()

    /**
     * The package that [simpleName] should be imported from, or `null` when no import can help.
     *
     * `null` covers three different situations, all of which end the same way for the caller: the
     * name is not a platform class, or it is a `java.lang` class that needs no import, or several
     * packages declare it and no single import is correct. [packagesOf] tells the first and third
     * apart from the second when the difference matters.
     */
    fun importPackageFor(simpleName: String): String? {
        val candidates = packagesOf(simpleName)
        if (candidates.isEmpty()) return null
        val only = candidates.singleOrNull() ?: return null
        return only.takeIf { it != IMPLICIT_PACKAGE }
    }

    private fun readPlatformClasses(): Map<String, List<String>> {
        val found = TreeMap<String, MutableList<String>>()
        try {
            val module = ModuleFinder.ofSystem().find(BASE_MODULE).orElse(null) ?: return emptyMap()
            module.open().use { reader -> collect(reader, found) }
        } catch (error: RuntimeException) {
            // A platform that cannot describe itself -- a stripped runtime, or one whose module
            // image is not a directory. Completion simply has no platform classes to offer, which is
            // a smaller loss than failing the completion it was asked for.
            return emptyMap()
        }
        return found.mapValues { (_, names) -> names.sorted() }
    }

    private fun collect(reader: ModuleReader, into: MutableMap<String, MutableList<String>>) {
        // `reader.list()` yields resource paths such as `java/lang/String.class`. A nested class is
        // `Outer$Inner.class`, and Neko has no syntax for naming one, so those are skipped rather
        // than offered as names that could not be written.
        reader.list()
            .filter { it.endsWith(".class") && !it.contains('$') }
            .forEach { resource ->
                val path = resource.removeSuffix(".class")
                val separator = path.lastIndexOf('/')
                if (separator <= 0) return@forEach
                val packageName = path.substring(0, separator).replace('/', '.')
                into.getOrPut(packageName) { mutableListOf() } += path.substring(separator + 1)
            }
    }
}

/**
 * A class the indexed module provides, named by its simple name and the package holding it.
 *
 * A pair rather than two parallel lists because the two halves are never useful apart: a completion
 * row has to show *both* — the name to insert and the package it comes from — and an import clause is
 * built from exactly the package half.
 */
data class ClassLocation(
    /** The name as written in source, e.g. `HashMap`. */
    val simpleName: String,
    /** The package it must be imported from, e.g. `java.util`. */
    val packageName: String,
)
